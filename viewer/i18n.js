export function translator(locale = "en") {
  const fr = locale.toLowerCase().startsWith("fr");
  const t = (key) => labels[key]?.[fr ? 1 : 0] ?? key;
  t.effect = (id) => effects[id]?.[fr ? 1 : 0] ?? "";
  t.role = (id) =>
    roleHelp[id === "adventurer2" ? "adventurer" : id]?.[fr ? 1 : 0] ?? "";
  t.fr = fr;
  return t;
}
